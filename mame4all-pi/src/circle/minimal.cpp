void gp2x_deinit(void)
{
	if(gp2x_screen8) free(gp2x_screen8);
	if(gp2x_screen15) free(gp2x_screen15);
	gp2x_screen8=0;
	gp2x_screen15=0;
}

void gp2x_set_video_mode(struct osd_bitmap *bitmap, int bpp,int width,int height)
{
	surface_width = width;
	surface_height = height;
	surface_depth = bitmap ? bitmap->depth : 16;

	gp2x_screen8=(unsigned char *) calloc(1, width*height);
	gp2x_screen15=(unsigned short *) calloc(1, width*height*2);

	cg_fb_set_mode(width, height);
}

void DisplayScreen(struct osd_bitmap *bitmap)
{
	extern int throttle;
	if (throttle) cg_wait_vsync();
	if (bitmap->depth == 8)
		cg_fb_present8(gp2x_screen8, (const unsigned short *) gp2x_palette, surface_width, surface_height);
	else
		cg_fb_present(gp2x_screen15, surface_width, surface_height);
}

void gp2x_frontend_init(void)
{
	surface_width = 640;
	surface_height = 480;
	gp2x_screen8=0;
	gp2x_screen15=(unsigned short *) calloc(1, 640*480*2);
	cg_fb_set_mode(640, 480);
}

void gp2x_frontend_deinit(void)
{
	if(gp2x_screen8) free(gp2x_screen8);
	if(gp2x_screen15) free(gp2x_screen15);
	gp2x_screen8=0;
	gp2x_screen15=0;
}

void FE_DisplayScreen(void)
{
	cg_fb_present(gp2x_screen15, surface_width, surface_height);
}


